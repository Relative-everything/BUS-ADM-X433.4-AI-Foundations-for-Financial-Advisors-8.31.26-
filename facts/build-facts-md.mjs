#!/usr/bin/env node
/**
 * build-facts-md.mjs — facts/FACTS.json -> facts/FACTS.md. FACTS.md is generated
 * and never hand-edited; this script is idempotent and --check is "run it and
 * diff", the same contract as scripts/build-appendix.mjs.
 *
 *   node facts/build-facts-md.mjs           # write facts/FACTS.md
 *   node facts/build-facts-md.mjs --check   # exit 1 if FACTS.md would change
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const FACTS = JSON.parse(readFileSync(join(HERE, 'FACTS.json'), 'utf8'));
const CHECK = process.argv.includes('--check');
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

const byVol = { high: [], medium: [], low: [] };
for (const r of FACTS) (byVol[r.volatility] || byVol.low).push(r);

const L = [];
L.push('# FACTS.md — the volatile-fact registry, rendered');
L.push('');
L.push(`**Generated from \`facts/FACTS.json\` by \`facts/build-facts-md.mjs\`. Do not edit this file; edit the JSON and re-run.** ${FACTS.length} records. Confidence: H verified against a fully fetched primary page in the build named by \`retrieved\`; M a primary-domain search snippet or a fully read secondary source; L weak; GAP not verified, value kept only as a claim to check. Volatility sets the re-verify window \`scripts/verify-facts.mjs\` enforces: high-volatility records must be re-retrieved within 14 days (each-session) or 180 days (term-start) of the \`--as-of\` date.`);
L.push('');
L.push('## The week-before ritual');
L.push('');
L.push('1. `node scripts/verify-facts.mjs --as-of <session date> --session <N>`.');
L.push('2. Re-open every high-volatility source listed as stale; if the value moved, change `value` and `statement`, move the old value into `retired_values`, and re-run the Phase 5 sweep on the pages `applies_to` names.');
L.push('3. Set `retrieved` to the date you read the source. `node facts/build-facts-md.mjs`. Commit FACTS.json and FACTS.md together.');
L.push('');
for (const vol of ['high', 'medium', 'low']) {
  const rows = byVol[vol];
  if (!rows.length) continue;
  L.push(`## Volatility: ${vol} (${rows.length})`);
  L.push('');
  L.push('| id | statement | value | conf. | retrieved | re-verify | applies to | retired values | source |');
  L.push('|---|---|---|---|---|---|---|---|---|');
  for (const r of rows) {
    const src = r.source_url ? `[${esc(r.source_title || r.source_url)}](${r.source_url})` : esc(r.source_title || '');
    L.push(`| \`${r.id}\` | ${esc(r.statement)} | ${esc(r.value)}${r.unit ? ' ' + esc(r.unit) : ''} | ${r.confidence} | ${r.retrieved} | ${r.reverify_before} | ${esc((r.applies_to || []).join(', '))} | ${(r.retired_values || []).length ? (r.retired_values || []).map((v) => '"' + esc(v) + '"').join(', ') : ''} | ${src} |`);
  }
  L.push('');
}
L.push('## Notes per record');
L.push('');
for (const r of FACTS) if (r.notes) L.push(`- \`${r.id}\`: ${esc(r.notes)}`);
L.push('');
const out = L.join('\n');
const target = join(HERE, 'FACTS.md');
const current = existsSync(target) ? readFileSync(target, 'utf8') : null;
if (CHECK) {
  if (current === out) { console.log('current       facts/FACTS.md'); process.exit(0); }
  console.log('STALE         facts/FACTS.md  (run node facts/build-facts-md.mjs)'); process.exit(1);
}
writeFileSync(target, out);
console.log(`${current === out ? 'unchanged' : 'written'}     facts/FACTS.md  ${FACTS.length} records`);
