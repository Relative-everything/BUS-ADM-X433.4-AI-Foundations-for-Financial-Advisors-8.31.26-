#!/usr/bin/env node
/**
 * build-readings.mjs — docs/next-term/readings.json -> the "Reading for Session N"
 * cards on the lesson pages (next-term-2027, Phase 10).
 *
 * Each page that should carry a reading card holds a sentinel pair:
 *
 *   <!-- READINGS:BEGIN s3 -->
 *   <!-- READINGS:END -->
 *
 * The id after BEGIN is the session the reading is FOR, so session-2's page
 * carries s3 and the setup page carries s1. The span between the sentinels is
 * this script's: idempotent, diffable, and never hand-edited. The visible
 * phrasing is "Reading for Session N", the one form the standing purge list
 * permits for a reading list (MAINTAINING.md, Tier B); no due-date words.
 *
 *   node scripts/build-readings.mjs           # write every card
 *   node scripts/build-readings.mjs --check   # exit 1 if a card is stale
 *
 * Jared's review: edit docs/next-term/readings.json (drop a row, change its
 * status from "tentative" to "approved", fix a title), run this script, commit
 * both. A row's status is kept in an HTML comment on the card, never shown.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');
const data = JSON.parse(readFileSync(join(REPO, 'docs/next-term/readings.json'), 'utf8'));
const PAGES = ['session-0.1/index.html', 'session-1/index.html', 'session-2/index.html',
               'session-3/index.html', 'session-4/index.html', 'session-5/index.html', 'index.html'];
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function card(n) {
  const rows = data.readings.filter((r) => String(r.session) === String(n));
  if (!rows.length) {
    /* A region with no rows (the wrap-up card after Session 5) renders a short card rather
       than failing: readings.json may legitimately assign nothing after the last session. */
    return [`<!-- generated by scripts/build-readings.mjs from docs/next-term/readings.json · 0 item(s) · do not edit between the sentinels -->`,
            `<div class="card" data-readings="s${n}">`, `  <span class="num">Reading after the course</span>`,
            `  <p class="dim">Nothing is assigned after the last session. The Wolfram essay and the Lee et al. study above are the ones to keep.</p>`, `</div>`].join('\n');
  }
  const L = [];
  L.push(`<!-- generated by scripts/build-readings.mjs from docs/next-term/readings.json · ${rows.length} item(s) · status ${[...new Set(rows.map((r) => r.status))].join('/')} · do not edit between the sentinels -->`);
  L.push(`<div class="card" data-readings="s${n}">`);
  L.push(`  <span class="num">Reading for Session ${n}</span>`);
  L.push(`  <h4>${rows.length === 1 ? 'One item' : rows.length === 2 ? 'Two items' : rows.length === 3 ? 'Three items' : rows.length === 4 ? 'Four items' : rows.length + ' items'}, about ${rows.reduce((a, r) => a + (r.minutes || 0), 0)} minutes</h4>`);
  L.push(`  <ul class="readlist">`);
  for (const r of rows) {
    const kind = r.type === 'video' ? 'Video' : 'Reading';
    const tail = [r.author, r.date].filter(Boolean).map(esc).join(', ');
    const flags = [r.type === 'video' && r.watch_before_class ? 'watch before class' : '', r.optional ? 'optional' : ''].filter(Boolean).join('; ');
    const chip = r.source_key && r.confidence ? ` <span class="conf ${String(r.confidence).toLowerCase()}" data-src="${esc(r.source_key)}">${esc(r.confidence)}</span>` : '';
    L.push(`    <li><b>${kind}</b> · <a href="${esc(r.url)}">${esc(r.title)}</a>${tail ? '. ' + tail : ''}. About ${r.minutes} min${flags ? ' (' + flags + ')' : ''}.${r.extra_urls ? ' Also: ' + r.extra_urls.map((u) => `<a href="${esc(u)}">${esc(u.replace(/^https?:\/\//, ''))}</a>`).join(', ') + '.' : ''}${chip}</li>`);
  }
  L.push(`  </ul>`);
  L.push(`</div>`);
  return L.join('\n');
}

let stale = 0, written = 0, seen = 0;
for (const rel of PAGES) {
  const path = join(REPO, rel);
  if (!existsSync(path)) continue;
  const text = readFileSync(path, 'utf8');
  const rx = /<!-- READINGS:BEGIN s([0-9.]+) -->[\s\S]*?<!-- READINGS:END -->/g;
  let out = text, m, found = 0;
  while ((m = rx.exec(text))) {
    found++;
    const next = `<!-- READINGS:BEGIN s${m[1]} -->\n${card(m[1])}\n<!-- READINGS:END -->`;
    out = out.replace(m[0], next);
  }
  if (!found) continue;
  seen += found;
  if (out === text) { console.log(`OK    current  ${rel}  (${found} card(s))`); continue; }
  if (CHECK) { console.log(`STALE          ${rel}`); stale++; }
  else { writeFileSync(path, out); console.log(`WROTE          ${rel}  (${found} card(s))`); written++; }
}
console.log(`summary: ${seen} card region(s) across ${PAGES.length} page(s); ${CHECK ? stale + ' stale' : written + ' written'}; ${data.readings.length} rows, ${data.readings.filter((r) => r.status === 'tentative').length} tentative`);
process.exit(CHECK && stale ? 1 : 0);
